export const ICON_CATALOG: IconEntry[] = RAW.map(([name, icon, extra]) => ({
  name,
  label: name.replace(/-/g, ' '),
  icon,
  keywords: `${name} ${extra ?? ''}`.toLowerCase(),
}))

const ICON_MAP: Record<string, LucideIcon> = Object.fromEntries(
  ICON_CATALOG.map((entry) => [entry.name, entry.icon]),
)

const RECENT_KEY = 'flow-builder-recent-icons'
const MAX_RECENT = 12

export function getLucideIcon(name: string | undefined, fallback: LucideIcon): LucideIcon {
  if (!name) return fallback
  return ICON_MAP[name] ?? fallback
}

export function searchIcons(query: string): IconEntry[] {
  const q = query.trim().toLowerCase()
  if (!q) return ICON_CATALOG
  return ICON_CATALOG.filter(
    (entry) => entry.keywords.includes(q) || entry.label.includes(q) || entry.name.includes(q),
  )
}

export function readRecentIcons(): string[] {
  try {
    const raw = localStorage.getItem(RECENT_KEY)
    if (!raw) return []
    const parsed = JSON.parse(raw) as unknown
    if (!Array.isArray(parsed)) return []
    return parsed.filter((v): v is string => typeof v === 'string' && v in ICON_MAP).slice(0, MAX_RECENT)
  } catch {
    return []
  }
}

export function pushRecentIcon(name: string): string[] {
  const next = [name, ...readRecentIcons().filter((n) => n !== name)].slice(0, MAX_RECENT)
  try {
    localStorage.setItem(RECENT_KEY, JSON.stringify(next))
  } catch {
    // ignore quota errors
  }
  return next
}
